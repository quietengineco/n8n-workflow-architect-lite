#!/usr/bin/env python3
"""Static checker for n8n workflow JSON (Quiet Engine Co., n8n Workflow Architect).

Standard library only. Makes no network calls, writes nothing, and reads nothing except the
workflow file(s) you name (or stdin). The node-version table is embedded below, so the script can
run from a pipe without any other skill files:  cat validate_workflow.py | python3 - workflow.json

Checks
  * JSON syntax (reports line and column)
  * workflow shape: "nodes" list, "connections" object, required node fields
  * duplicate node names and duplicate node ids
  * connection references: source and target names exist, output/input indexes are valid
  * connections keyed by node id instead of node name (a common hand-editing mistake)
  * credentials: nodes that need a credential have a "credentials" block with
    {"id", "name"}; placeholders are reported so you remember to replace them
  * likely hardcoded secrets (API keys, bearer tokens) in node parameters
  * trigger present, unreachable nodes, sticky notes present
  * retry settings (n8n clamps maxTries to 2-5 and waitBetweenTries to 0-5000 ms)
  * typeVersion against the embedded node-versions table (when this build includes one)

Usage
  python3 validate_workflow.py workflow.json [more.json ...]
  python3 validate_workflow.py --json workflow.json      # machine-readable report
  python3 validate_workflow.py --strict workflow.json    # warnings also fail
  python3 validate_workflow.py - < workflow.json                # workflow JSON on stdin
  cat validate_workflow.py | python3 - workflow.json            # script itself on stdin

Exit codes: 0 = no errors, 1 = errors found (or warnings with --strict),
2 = a file could not be read or parsed as JSON / bad arguments.
"""
import argparse
import json
import re
import sys

VERSION = "1.1.0"

# BEGIN EMBEDDED NODE VERSIONS (generated by dev/build_validator.py; do not edit by hand)
EMBEDDED_VERSIONS = {}
# END EMBEDDED NODE VERSIONS

# Node types that cannot do their job without a credential. Used when no versions
# table is available; the table (if present) adds more types.
CREDENTIAL_REQUIRED = {
    "n8n-nodes-base.airtable", "n8n-nodes-base.discord", "n8n-nodes-base.emailReadImap",
    "n8n-nodes-base.emailSend", "n8n-nodes-base.github", "n8n-nodes-base.githubTrigger",
    "n8n-nodes-base.gmail", "n8n-nodes-base.gmailTrigger", "n8n-nodes-base.googleDrive",
    "n8n-nodes-base.googleSheets", "n8n-nodes-base.googleSheetsTrigger",
    "n8n-nodes-base.hubspot", "n8n-nodes-base.jira", "n8n-nodes-base.mattermost",
    "n8n-nodes-base.microsoftExcel", "n8n-nodes-base.microsoftOutlook",
    "n8n-nodes-base.mySql", "n8n-nodes-base.notion", "n8n-nodes-base.postgres",
    "n8n-nodes-base.redis", "n8n-nodes-base.shopify", "n8n-nodes-base.slack",
    "n8n-nodes-base.stripe", "n8n-nodes-base.telegram", "n8n-nodes-base.todoist",
    "n8n-nodes-base.trello",
}

# Trigger node types (start a workflow). Anything whose type ends in "Trigger" or
# is a webhook/form/chat entry point also counts.
TRIGGER_TYPES = {
    "n8n-nodes-base.webhook", "n8n-nodes-base.formTrigger", "n8n-nodes-base.manualTrigger",
    "n8n-nodes-base.scheduleTrigger", "n8n-nodes-base.errorTrigger",
    "n8n-nodes-base.executeWorkflowTrigger", "n8n-nodes-base.emailReadImap",
    "n8n-nodes-base.rssFeedReadTrigger", "@n8n/n8n-nodes-langchain.chatTrigger",
    "n8n-nodes-base.cron", "n8n-nodes-base.interval", "n8n-nodes-base.start",
}

STICKY = "n8n-nodes-base.stickyNote"
PLACEHOLDER_RE = re.compile(r"(REPLACE|PLACEHOLDER|CHANGE[_-]?ME|YOUR[_-]|TODO|<.+>|^$)", re.I)
SECRET_PATTERNS = [
    ("OpenAI-style key", re.compile(r"\bsk-(?:proj-|ant-)?[A-Za-z0-9_\-]{20,}")),
    ("Slack token", re.compile(r"\bxox[abprs]-[A-Za-z0-9\-]{10,}")),
    ("GitHub token", re.compile(r"\b(?:ghp|gho|ghu|ghs|github_pat)_[A-Za-z0-9_]{20,}")),
    ("AWS access key id", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("Google API key", re.compile(r"\bAIza[0-9A-Za-z_\-]{35}\b")),
    ("Stripe secret key", re.compile(r"\b[sr]k_live_[0-9A-Za-z]{16,}")),
    ("Bearer token", re.compile(r"Bearer\s+(?!\{\{)[A-Za-z0-9_\-\.=]{24,}")),
    ("Private key block", re.compile(r"-{5}BEGIN [A-Z ]*PRIVATE KEY-{5}")),
]
SECRET_PARAM_NAMES = re.compile(r"(api[_-]?key|apikey|secret|password|passwd|token|authorization)$", re.I)


class Report:
    def __init__(self, path):
        self.path = path
        self.items = []  # (level, code, message)

    def add(self, level, code, msg):
        self.items.append({"level": level, "code": code, "message": msg})

    def error(self, code, msg):
        self.add("error", code, msg)

    def warn(self, code, msg):
        self.add("warning", code, msg)

    def info(self, code, msg):
        self.add("info", code, msg)

    def count(self, level):
        return sum(1 for i in self.items if i["level"] == level)


def node_table():
    """The embedded node-version table ({} in builds without one)."""
    return EMBEDDED_VERSIONS


def is_trigger(node_type, table):
    if node_type in TRIGGER_TYPES:
        return True
    entry = table.get(node_type)
    if entry and entry.get("trigger"):
        return True
    return node_type.endswith("Trigger")


def walk_strings(value, path=""):
    """Yield (path, key, string) for every string inside nested parameters."""
    if isinstance(value, dict):
        for k, v in value.items():
            p = f"{path}.{k}" if path else str(k)
            if isinstance(v, str):
                yield p, str(k), v
            else:
                yield from walk_strings(v, p)
    elif isinstance(value, list):
        for i, v in enumerate(value):
            p = f"{path}[{i}]"
            if isinstance(v, str):
                yield p, "", v
            else:
                yield from walk_strings(v, p)


def check_secrets(rep, node):
    name = node.get("name", "?")
    for p, key, s in walk_strings(node.get("parameters", {})):
        for label, rx in SECRET_PATTERNS:
            if rx.search(s):
                rep.error("hardcoded-secret",
                          f'node "{name}": parameters.{p} looks like a {label}. '
                          "Move it into an n8n credential and reference that instead.")
                break
        else:
            # A literal value under a secret-looking parameter name (not an expression).
            if key and SECRET_PARAM_NAMES.search(key) and s and not s.startswith("=") \
                    and "{{" not in s and len(s) >= 12 and not PLACEHOLDER_RE.search(s):
                rep.warn("possible-secret",
                         f'node "{name}": parameters.{p} holds a literal value under a '
                         "secret-like name. Use a credential or an expression instead.")


def check_header_pairs(rep, node):
    already = any(i["code"] == "hardcoded-secret" and f'node "{node.get("name")}"' in i["message"] for i in rep.items)
    if already:
        return
    params = node.get("parameters", {})
    hp = params.get("headerParameters", {})
    pairs = hp.get("parameters", []) if isinstance(hp, dict) else []
    for pair in pairs if isinstance(pairs, list) else []:
        if not isinstance(pair, dict):
            continue
        hname = str(pair.get("name", ""))
        hval = pair.get("value", "")
        if SECRET_PARAM_NAMES.search(hname.replace("-", "")) or hname.lower() in ("x-api-key", "authorization"):
            if isinstance(hval, str) and hval and "{{" not in hval and not PLACEHOLDER_RE.search(hval):
                rep.error("hardcoded-secret",
                          f'node "{node.get("name")}": header "{hname}" has a literal value. '
                          "Use a Header Auth credential (httpHeaderAuth) instead.")


def check_credentials(rep, node, table):
    ntype = node.get("type", "")
    name = node.get("name", "?")
    creds = node.get("credentials")
    entry = table.get(ntype, {})
    required = ntype in CREDENTIAL_REQUIRED or bool(entry.get("credentialsRequired"))
    params = node.get("parameters", {}) if isinstance(node.get("parameters"), dict) else {}

    if ntype == "n8n-nodes-base.httpRequest":
        auth = params.get("authentication")
        if auth in ("genericCredentialType", "predefinedCredentialType"):
            required = True

    if creds is None:
        if required:
            rep.error("missing-credentials",
                      f'node "{name}" ({ntype}) needs a credential but has no "credentials" block. '
                      'Add e.g. "credentials": {"<credentialType>": {"id": "REPLACE_WITH_CREDENTIAL_ID", '
                      '"name": "<label>"}} and connect the real credential after import.')
        return
    if not isinstance(creds, dict) or not creds:
        rep.error("bad-credentials", f'node "{name}": "credentials" must be a non-empty object.')
        return
    allowed = set(entry.get("credentialTypes", []))
    for ctype, cval in creds.items():
        if allowed and ctype not in allowed and ntype != "n8n-nodes-base.httpRequest":
            rep.warn("unknown-credential-type",
                     f'node "{name}": credential type "{ctype}" is not one this node accepts '
                     f'({", ".join(sorted(allowed))}).')
        if not isinstance(cval, dict) or "name" not in cval:
            rep.error("bad-credentials",
                      f'node "{name}": credentials.{ctype} must be an object with "id" and "name".')
            continue
        cid = cval.get("id")
        if cid is None or (isinstance(cid, str) and PLACEHOLDER_RE.search(cid)):
            rep.info("credential-placeholder",
                     f'node "{name}": credentials.{ctype} is a placeholder; select a real '
                     "credential in n8n after importing.")


def check_retry(rep, node):
    name = node.get("name", "?")
    if node.get("retryOnFail"):
        mt = node.get("maxTries")
        wt = node.get("waitBetweenTries")
        if mt is not None and (not isinstance(mt, (int, float)) or mt < 2 or mt > 5):
            rep.warn("retry-clamped",
                     f'node "{name}": maxTries={mt}. n8n clamps this to 2-5 (default 3).')
        if wt is not None and (not isinstance(wt, (int, float)) or wt < 0 or wt > 5000):
            rep.warn("retry-clamped",
                     f'node "{name}": waitBetweenTries={wt}. n8n clamps this to 0-5000 ms '
                     "(default 1000). For longer back-off use a Wait node loop.")
    elif "maxTries" in node or "waitBetweenTries" in node:
        rep.warn("retry-off", f'node "{name}": maxTries/waitBetweenTries are set but retryOnFail is not true, so they do nothing.')
    if "onError" in node and node["onError"] not in ("continueErrorOutput", "continueRegularOutput", "stopWorkflow"):
        rep.error("bad-onError", f'node "{name}": onError="{node["onError"]}" is not one of '
                  "continueErrorOutput, continueRegularOutput, stopWorkflow.")
    if node.get("continueOnFail") is True and "onError" in node:
        rep.warn("legacy-continueOnFail",
                 f'node "{name}": has both legacy continueOnFail and onError; onError wins. Remove continueOnFail.')


def output_count(node):
    """Rough upper bound for the number of main outputs a node can have."""
    t = node.get("type", "")
    p = node.get("parameters", {}) if isinstance(node.get("parameters"), dict) else {}
    extra = 1 if node.get("onError") == "continueErrorOutput" else 0
    if t == "n8n-nodes-base.if":
        return 2 + extra
    if t == "n8n-nodes-base.filter":
        return (1 if float(node.get("typeVersion", 2) or 2) >= 2 else 2) + extra
    if t == "n8n-nodes-base.splitInBatches":
        return 2 + extra
    if t == "n8n-nodes-base.switch":
        rules = p.get("rules", {})
        vals = rules.get("values", rules.get("rules", [])) if isinstance(rules, dict) else []
        n = len(vals) if isinstance(vals, list) and vals else 4
        if p.get("options", {}).get("fallbackOutput") == "extra":
            n += 1
        return max(n, int(p.get("numberOutputs", 0) or 0)) + extra
    if t == "n8n-nodes-base.compareDatasets":
        return 4
    return 1 + extra


def validate_workflow(wf, rep, table):
    if not isinstance(wf, dict):
        rep.error("not-object", "workflow must be a JSON object.")
        return
    if "nodes" not in wf:
        rep.error("no-nodes", 'missing top-level "nodes" array.')
        return
    nodes = wf["nodes"]
    if not isinstance(nodes, list):
        rep.error("no-nodes", '"nodes" must be an array.')
        return
    conns = wf.get("connections")
    if conns is None:
        rep.error("no-connections", 'missing top-level "connections" object (use {} if there are none).')
        conns = {}
    elif not isinstance(conns, dict):
        rep.error("no-connections", '"connections" must be an object keyed by node name.')
        conns = {}
    if not wf.get("name"):
        rep.warn("no-name", 'workflow has no "name"; n8n import will still work but the UI shows an empty name.')

    names, ids = {}, {}
    for i, n in enumerate(nodes):
        where = f"nodes[{i}]"
        if not isinstance(n, dict):
            rep.error("bad-node", f"{where} is not an object.")
            continue
        nm = n.get("name")
        label = f'{where} "{nm}"' if nm else where
        for field, typ in (("name", str), ("type", str), ("parameters", dict)):
            if field not in n:
                rep.error("node-field", f'{label}: missing "{field}".')
            elif not isinstance(n[field], typ):
                rep.error("node-field", f'{label}: "{field}" has the wrong type.')
        if "typeVersion" not in n:
            rep.error("node-field", f'{label}: missing "typeVersion".')
        elif isinstance(n["typeVersion"], bool) or not isinstance(n["typeVersion"], (int, float)):
            rep.error("node-field", f'{label}: "typeVersion" must be a number, not {json.dumps(n["typeVersion"])}.')
        pos = n.get("position")
        if not (isinstance(pos, list) and len(pos) == 2 and all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in pos)):
            rep.error("node-field", f'{label}: "position" must be [x, y] numbers.')
        if "id" not in n:
            rep.warn("node-id", f'{label}: no "id". n8n generates one on import, but give each node a stable UUID.')
        elif not isinstance(n["id"], str) or not n["id"]:
            rep.error("node-id", f'{label}: "id" must be a non-empty string.')
        else:
            if n["id"] in ids:
                rep.error("duplicate-id", f'{label}: id "{n["id"]}" is also used by "{ids[n["id"]]}".')
            ids[n["id"]] = nm
        if isinstance(nm, str):
            if nm in names:
                rep.error("duplicate-name", f'duplicate node name "{nm}" ({names[nm]} and {where}). '
                          "Connections are keyed by name, so names must be unique.")
            else:
                names[nm] = where
        t = n.get("type")
        if isinstance(t, str):
            if "." not in t:
                rep.error("bad-type", f'{label}: type "{t}" should be a full id such as "n8n-nodes-base.set".')
            elif t in table and isinstance(n.get("typeVersion"), (int, float)):
                known = table[t].get("versions", [])
                if known and n["typeVersion"] not in known:
                    rep.warn("unknown-typeVersion",
                             f'{label}: {t} typeVersion {n["typeVersion"]} is not in the verified list {known}. '
                             "It may fail to import or open as an unknown node.")
            if t != STICKY:
                check_credentials(rep, n, table)
                check_retry(rep, n)
            check_secrets(rep, n)
            check_header_pairs(rep, n)

    real_nodes = {n.get("name"): n for n in nodes if isinstance(n, dict) and n.get("type") != STICKY and isinstance(n.get("name"), str)}
    stickies = [n for n in nodes if isinstance(n, dict) and n.get("type") == STICKY]

    # Connections
    incoming = {k: 0 for k in real_nodes}
    adjacency = {k: set() for k in real_nodes}
    for src, outputs in conns.items():
        if src not in names:
            hint = ""
            if src in ids:
                hint = f' (that is the id of node "{ids[src]}"; connections must use the node name)'
            rep.error("bad-connection-source", f'connections has source "{src}" but no node has that name{hint}.')
            continue
        if not isinstance(outputs, dict):
            rep.error("bad-connection", f'connections["{src}"] must be an object like {{"main": [[...]]}}.')
            continue
        for ctype, branches in outputs.items():
            if not isinstance(branches, list):
                rep.error("bad-connection", f'connections["{src}"]["{ctype}"] must be a list of output lists.')
                continue
            if ctype == "main" and src in real_nodes and len(branches) > output_count(real_nodes[src]):
                rep.warn("extra-outputs", f'"{src}" has {len(branches)} output lists but this node type normally has '
                         f'{output_count(real_nodes[src])}. Check for a misplaced branch.')
            for bi, branch in enumerate(branches):
                if branch is None:
                    continue
                if not isinstance(branch, list):
                    rep.error("bad-connection", f'connections["{src}"]["{ctype}"][{bi}] must be a list.')
                    continue
                for link in branch:
                    if not isinstance(link, dict) or "node" not in link:
                        rep.error("bad-connection", f'connections["{src}"]["{ctype}"][{bi}] has an entry without "node".')
                        continue
                    tgt = link["node"]
                    if tgt not in names:
                        hint = f' (that is the id of node "{ids[tgt]}")' if tgt in ids else ""
                        rep.error("bad-connection-target", f'"{src}" connects to "{tgt}", which does not exist{hint}.')
                        continue
                    if "type" not in link:
                        rep.warn("bad-connection", f'link "{src}" -> "{tgt}" has no "type" (expected "{ctype}").')
                    idx = link.get("index", 0)
                    if not isinstance(idx, int) or isinstance(idx, bool) or idx < 0:
                        rep.error("bad-connection", f'link "{src}" -> "{tgt}" has invalid index {json.dumps(idx)}.')
                    elif idx > 0 and tgt in real_nodes and real_nodes[tgt].get("type") != "n8n-nodes-base.merge":
                        rep.warn("input-index", f'link "{src}" -> "{tgt}" uses input index {idx}; only Merge-type nodes have more than one input.')
                    if tgt in real_nodes and src in real_nodes:
                        if is_trigger(real_nodes[tgt].get("type", ""), table):
                            rep.error("into-trigger", f'"{src}" connects into trigger node "{tgt}"; triggers cannot have inputs.')
                        incoming[tgt] += 1
                        adjacency[src].add(tgt)
                    if tgt in names and tgt not in real_nodes:
                        rep.error("bad-connection-target", f'"{src}" connects to sticky note "{tgt}".')

    triggers = [k for k, n in real_nodes.items() if is_trigger(n.get("type", ""), table)]
    if real_nodes and not triggers:
        rep.warn("no-trigger", "no trigger node. That is fine for a sub-workflow snippet, but a runnable workflow needs one "
                 "(Manual Trigger for testing, Execute Workflow Trigger for sub-workflows).")
    # Reachability from triggers.
    seen, stack = set(triggers), list(triggers)
    while stack:
        cur = stack.pop()
        for nxt in adjacency.get(cur, ()):
            if nxt not in seen:
                seen.add(nxt)
                stack.append(nxt)
    if triggers:
        for k, n in real_nodes.items():
            if k not in seen:
                rep.warn("unreachable", f'node "{k}" is not reachable from any trigger, so it will never run.')
    if real_nodes and not stickies:
        rep.warn("no-sticky-notes", "no sticky notes. Add at least an overview note (what it does, setup, credentials); "
                 "the n8n template library requires them.")
    settings = wf.get("settings")
    if isinstance(settings, dict) and settings.get("executionOrder") not in (None, "v1"):
        rep.info("execution-order", f'settings.executionOrder is "{settings.get("executionOrder")}"; new workflows use "v1".')
    rep.info("summary", f"{len(real_nodes)} nodes, {len(stickies)} sticky notes, {len(triggers)} trigger(s).")


def line_col_hint(text, err):
    lines = text.splitlines()
    ln = err.lineno
    snippet = lines[ln - 1] if 0 < ln <= len(lines) else ""
    return f"line {err.lineno}, column {err.colno}: {err.msg}\n    {snippet.strip()[:120]}"


def read_input(path):
    """Return the text of a workflow file, or of stdin when path is "-"."""
    if path == "-":
        text = sys.stdin.read()
        if not text.strip():
            raise OSError("stdin is empty. If you piped this script into python3, pass the workflow "
                          "as a file argument instead of '-'.")
        return text.lstrip("\ufeff")
    with open(path, encoding="utf-8-sig") as fh:
        return fh.read()


def validate_file(path, table):
    rep = Report("<stdin>" if path == "-" else path)
    try:
        text = read_input(path)
    except OSError as exc:
        rep.error("read-error", str(exc))
        return rep, True
    try:
        data = json.loads(text)
    except json.JSONDecodeError as exc:
        rep.error("json-syntax", line_col_hint(text, exc))
        return rep, True
    if isinstance(data, list):  # `n8n export:workflow --all` writes an array
        if not data:
            rep.error("empty", "file contains an empty array.")
        for i, wf in enumerate(data):
            sub = Report(f"{path}[{i}]")
            validate_workflow(wf, sub, table)
            for item in sub.items:
                item = dict(item)
                item["message"] = f"[workflow {i}] " + item["message"]
                rep.items.append(item)
    else:
        validate_workflow(data, rep, table)
    return rep, False


def main(argv=None):
    ap = argparse.ArgumentParser(description="Check n8n workflow JSON before importing it.")
    ap.add_argument("files", nargs="+", help='workflow .json files, or "-" to read one workflow from stdin')
    ap.add_argument("--json", action="store_true", help="print a JSON report")
    ap.add_argument("--strict", action="store_true", help="treat warnings as failures")
    ap.add_argument("--quiet", action="store_true", help="hide info lines")
    ap.add_argument("--version", action="version", version=VERSION)
    args = ap.parse_args(argv)

    if args.files.count("-") > 1:
        ap.error('"-" (stdin) can only be given once')
    table = node_table()
    reports, fatal = [], False
    for f in args.files:
        rep, bad = validate_file(f, table)
        fatal = fatal or bad
        reports.append(rep)

    failed = any(r.count("error") or (args.strict and r.count("warning")) for r in reports)
    if args.json:
        out = [{"file": r.path, "errors": r.count("error"), "warnings": r.count("warning"),
                "ok": not (r.count("error") or (args.strict and r.count("warning"))), "items": r.items} for r in reports]
        print(json.dumps({"validator": VERSION, "versionsTable": bool(table), "results": out}, indent=2))
    else:
        for r in reports:
            status = "FAIL" if (r.count("error") or (args.strict and r.count("warning"))) else "OK"
            print(f"{status}  {r.path}  ({r.count('error')} errors, {r.count('warning')} warnings)")
            for it in r.items:
                if args.quiet and it["level"] == "info":
                    continue
                print(f"  {it['level'].upper():7} [{it['code']}] {it['message']}")
        if not table:
            print("note: this build has no node-versions table, so typeVersion checks were skipped.")
    if fatal:
        return 2
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
